#!/bin/sh
# Copy the rendered film into the site: WebP frames at two widths, a compact
# film.json per chapter, and lib/film.ts with each chapter's frame count.
#   film/publish.sh
# Reads film/out/<dir>/frames/*.png and film/out/<dir>/film.json (see render_queue.sh).
set -e
cd "$(dirname "$0")/.."
PY=/Applications/Blender.app/Contents/Resources/5.2/python/bin/python3.13
CHAPTERS="01-brain:brain-tumor-ai 02-legal:enter-reports 03-kernelnet:kernelnet 04-stellar:stellar"

for pair in $CHAPTERS; do
  dir=${pair%%:*}; slug=${pair##*:}
  # Flatten onto the page's paper colour so the film has no box of its own
  # (the stage feathers its edges into the page). Transparent WebP would
  # do it too, but the soft shadows make it five times heavier, or banded.
  # cwebp's -blend_alpha leaves the background black, hence ffmpeg.
  mkdir -p "film/out/$dir/flat"
  ls film/out/$dir/frames/*.png | xargs -P 8 -I{} sh -c \
    'ffmpeg -loglevel error -y -f lavfi -i color=0xFCFCFB:s=1920x1080 -i "$1" -filter_complex overlay=format=auto -frames:v 1 "film/out/'$dir'/flat/$(basename "$1")"' _ {}
  for w in 960 1600; do
    mkdir -p "public/film/$slug/$w"
    ls film/out/$dir/flat/*.png | xargs -P 8 -I{} sh -c \
      'cwebp -quiet -q 75 -m 6 -resize '$w' 0 "$1" -o "public/film/'$slug/$w'/$(basename "$1" .png).webp"' _ {}
  done
  echo "$slug: $(ls public/film/$slug/960 | wc -l | tr -d ' ') frames, $(du -sh public/film/$slug | cut -f1)"
done

$PY - "$CHAPTERS" <<'EOF'
import json, sys
chapters = [p.split(":") for p in sys.argv[1].split()]
counts = []
for d, slug in chapters:
    j = json.load(open(f"film/out/{d}/film.json"))
    # anchors: [x, y] in 0..1 of the frame, or 0 when the point is behind the camera
    j["anchors"] = {k: [[round(p[0], 4), round(p[1], 4)] if p[2] > 0 else 0 for p in v] for k, v in j["anchors"].items()}
    json.dump(j, open(f"public/film/{slug}/film.json", "w"), separators=(",", ":"))
    counts.append((slug, j["frames"]))
with open("lib/film.ts", "w") as f:
    f.write("// Generated by film/publish.sh from the Blender renders. Do not edit.\n")
    f.write("// Frames live in public/film/<slug>/<width>/NNNN.webp with labels in film.json.\n\n")
    f.write("export const filmChapters = [\n")
    for slug, n in counts:
        f.write(f"  {{ slug: '{slug}', frames: {n} }},\n")
    f.write("] as const;\n\nexport const filmWidths = [960, 1600] as const;\n")
print(open("lib/film.ts").read())
EOF
du -sh public/film
